// Every language selectable in Settings > General. Adding a new one is just
// a new key in I18N above plus an entry here.
const SUPPORTED_LANGUAGES = ['en', 'es', 'fr', 'de', 'ru'];

// Turns a BCP-47 locale tag ("ru-RU", "en-US", "de-DE"...) into one of our
// supported language codes, falling back to English for anything we don't
// have strings for yet.
function detectSystemLanguage(localeTag) {
  const base = (localeTag || 'en').toLowerCase().split('-')[0];
  return SUPPORTED_LANGUAGES.indexOf(base) !== -1 ? base : 'en';
}

// Looks up `key` in the given language, falling back to English, then to
// the key itself so a missing translation never renders as blank.
// Supports {0}, {1}... placeholders for simple templating (e.g. "Step {0} of {1}").
function i18nString(lang, key, ...args) {
  const dict = I18N[lang] || I18N.en;
  let str = dict[key] !== undefined ? dict[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
  args.forEach((arg, i) => { str = str.replace('{' + i + '}', arg); });
  return str;
}
